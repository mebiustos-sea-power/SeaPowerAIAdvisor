using System;
using System.Collections.Generic;
using System.Linq;
using Newtonsoft.Json.Linq;
using static SeaPowerAIAdvisor.BattleValue;

namespace SeaPowerAIAdvisor;

// Read only confirmed own units. Query sessions retain JSON, never live orders or formations.
internal static class BattleMovementReader
{
    internal static (JArray Plans, JArray Routes) Capture(IReadOnlyList<(object Object, string Id)> units)
    {
        string? Resolve(object? value) => units.FirstOrDefault(u => ReferenceEquals(u.Object, value)).Id;
        var plans = new JArray();
        var routes = new JArray();
        foreach (var (unit, id) in units)
        {
            var formation = Member(unit, "Formation");
            var station = formation == null ? null : Member(formation, "LeaderStation");
            var leader = station == null ? null : Member(station, "UnitObject");
            var isLeader = (bool)Required(unit, "IsFormationLeader");
            var follows = !isLeader && (bool)Required(unit, "FollowingFormation");
            var routeId = follows ? Resolve(leader) : id;
            plans.Add(new JObject
            {
                ["id"] = id,
                ["formation_name"] = formation == null ? JValue.CreateNull() : Text((string?)Member(formation, "Name")),
                ["formation_leader_id"] = Text(Resolve(leader)),
                ["movement_mode"] = isLeader ? "formation_leader" : follows ? "following_formation" :
                    formation != null ? "independent_in_formation" : "independent",
                ["route_unit_id"] = Text(routeId)
            });
            // Formation stations generate short-term steering points, not the follower's own destination.
            if (!follows) routes.Add(new JObject { ["id"] = id, ["waypoints"] = Waypoints(unit, Resolve) });
        }
        return (plans, routes);
    }

    private static JArray Waypoints(object unit, Func<object?, string?> resolve)
    {
        var result = new JArray();
        var root = Member(unit, "_userRoot");
        if (root == null) return result;
        foreach (var view in Rows(Required(root, "TaskViewModels")))
        {
            if (view == null || Member(view, "Task") is not object task) continue;
            var relative = Is(task, "GoToRelativePoint");
            if (!relative && !Is(task, "GoToWaypointTask")) continue;
            var row = new JObject { ["sequence"] = result.Count + 1,
                ["kind"] = relative ? "relative_waypoint" : "waypoint", ["position"] = JValue.CreateNull(),
                ["generated"] = (bool)Required(task, "_isAutogenerated") };
            object? position;
            if (relative)
            {
                var parent = Parameter(task, "target");
                var parentId = resolve(parent);
                row["relative_to_unit_id"] = Text(parentId);
                // A relative getter may dereference its parent. Only resolve own-unit or patrol-zone geometry.
                position = Member(task, "_patrolZone") != null || parentId != null
                    ? Member(task, "WaypointPosition") : parent == null ? Parameter(task, "targetPosition") : null;
            }
            else if ((bool)RequiredParameter(task, "_setCourse") || (bool)RequiredParameter(task, "_setTurn"))
            {
                var turn = (bool)RequiredParameter(task, "_setTurn");
                row["kind"] = turn ? "turn" : "set_course";
                row[turn ? "turn_deg" : "course_deg"] = Number(RequiredParameter(task, "_course"));
                // These destinations are computed when the task starts; an unexecuted stored point can be a placeholder.
                position = null;
            }
            else if ((bool)RequiredParameter(task, "_toCurrentPosition"))
            {
                var parent = Parameter(task, "_parentObject");
                var parentId = resolve(parent);
                row["kind"] = "to_unit_position";
                row["target_unit_id"] = Text(parentId);
                position = parentId == null ? null : Required(Required(parent!, "Position"), "Value");
            }
            else position = Required(task, "WaypointPosition");
            if (position != null) row["position"] = AdvisorInputBuilder.Position(new MapPosition(
                Number(Required(position, "Latitude")), Number(Required(position, "Longitude"))));
            result.Add(row);
        }
        return result;
    }

    private static bool Is(object value, string name)
    {
        for (var type = value.GetType(); type != null; type = type.BaseType)
            if (type.Name == name) return true;
        return false;
    }
    private static object? Parameter(object task, string name)
    {
        var parameter = Member(task, name);
        return parameter == null ? null : Member(parameter, "value");
    }
    private static object RequiredParameter(object task, string name) => Parameter(task, name)
        ?? throw new InvalidOperationException("A movement task parameter is unavailable: " + name);
    private static JValue Text(string? value) => value == null ? JValue.CreateNull() : new JValue(value);
}
