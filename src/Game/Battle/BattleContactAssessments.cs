using System;
using System.Collections.Generic;
using System.Linq;
using Noesis;
using SeaPower;
using SeapowerUI;
using static SeaPowerAIAdvisor.BattleValue;

namespace SeaPowerAIAdvisor;

// Adds a contact-specific consultation entry point to each existing information window.
internal sealed class BattleContactAssessments : IDisposable
{
    private readonly Func<AdvisorWindow> advisor;
    private readonly Func<AdvisorInformation> information;
    private readonly Action<Action> guard;
    private readonly Dictionary<object, (object Vehicle, AdvisorContactButton Button, RoutedEventHandler Handler)> buttons = new();
    private string language = "";
    private AdvisorText? text;

    internal BattleContactAssessments(Func<AdvisorWindow> advisor, Func<AdvisorInformation> information, Action<Action> guard)
    { this.advisor = advisor; this.information = information; this.guard = guard; }

    internal void Tick(DependencyObject root, WindowHost host)
    {
        var currentLanguage = GameLanguage.Read();
        if (text == null || language != currentLanguage) { language = currentLanguage; text = AdvisorText.Load(language); }
        var models = host.Windows.Where(m => m.GetType().FullName == "SeapowerUI.ViewModels.VehicleInfoViewModel").ToArray();
        foreach (var closed in buttons.Keys.Where(m => !models.Contains(m)).ToArray())
        {
            var entry = buttons[closed]; entry.Button.Control.Click -= entry.Handler;
            entry.Button.Dispose(); buttons.Remove(closed);
        }
        foreach (var model in models)
        {
            if (buttons.ContainsKey(model)) continue;
            var window = FindWindow(root, model);
            if (window == null) continue; // WindowHost stores view models; their windows are generated by a data template.
            var reset = FindReset(window, Required(model, "ResetTma"));
            if (reset == null) continue; // The window's data template may not yet have been instantiated.
            var vehicle = Required(model, "forVeh");
            var button = new AdvisorContactButton(reset);
            RoutedEventHandler handler = (_, _) => guard(() => Request(model, vehicle));
            button.Control.Click += handler;
            buttons.Add(model, (vehicle, button, handler));
        }
        if (buttons.Count == 0) return;
        var current = advisor();
        foreach (var entry in buttons)
            entry.Value.Button.Update(text!.Format("contact.assessment_button", current.DisplayName),
                CanRequest(entry.Key, entry.Value.Vehicle, current));
    }

    private bool CanRequest(object model, object vehicle, AdvisorWindow current)
    {
        if (FindSignatures(model) == null) return false;
        var map = Member(vehicle, "ViewModel");
        return map != null && BattleContactAssessment.IsAvailable(information(),
            (bool)Required(Required(vehicle, "Identified"), "Value"), !current.CanConsult,
            Code(Required(map, "VisualPosture")), (bool)Required(Required(vehicle, "BaseObject"), "IsDestroyed"), Code(Required(map, "VisualType")));
    }

    private void Request(object model, object vehicle)
    {
        var current = advisor();
        if (!CanRequest(model, vehicle, current)) return;
        var signatures = FindSignatures(model) ?? throw new InvalidOperationException("The displayed contact signatures are unavailable.");
        var evidence = BattleContactEvidenceReader.Capture(signatures, SensorMetadataProvider.Instance,
            key => LanguageResourceHandler.Instance.getSignatureName(key, true));
        var track = (int)Required(vehicle, "Id");
        var context = new Newtonsoft.Json.Linq.JObject
        {
            ["track_number"] = track, ["evidence"] = evidence,
            ["captured_at_utc"] = AdvisorInputBuilder.Time(SeaPower.Environment.Instance.DateTime)
        };
        current.ConsultContext("contact_assessment", text!.Format("contact.assessment_request", track), context);
    }

    private static object? FindSignatures(object model) => Rows(Required(model, "StateComponents"))
        .SingleOrDefault(s => s.GetType().FullName == "SeapowerUI.ViewModels.SignaturesViewModel");
    private static Window? FindWindow(DependencyObject node, object model)
    {
        if (node is Window window && ReferenceEquals(window.DataContext, model)) return window;
        for (var i = 0; i < VisualTreeHelper.GetChildrenCount(node); i++)
        {
            var found = FindWindow(VisualTreeHelper.GetChild(node, i), model);
            if (found != null) return found;
        }
        return null;
    }
    private static Button? FindReset(DependencyObject node, object command)
    {
        if (node is Button button && ReferenceEquals(button.Command, command)) return button;
        for (var i = 0; i < VisualTreeHelper.GetChildrenCount(node); i++)
        {
            var found = FindReset(VisualTreeHelper.GetChild(node, i), command);
            if (found != null) return found;
        }
        return null;
    }
    internal void Suspend()
    { foreach (var entry in buttons.Values) entry.Button.Control.IsEnabled = false; }
    public void Dispose()
    {
        foreach (var entry in buttons.Values)
        { entry.Button.Control.Click -= entry.Handler; entry.Button.Dispose(); }
        buttons.Clear();
    }
}
